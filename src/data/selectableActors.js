const abilities = (strength, dexterity, constitution, intelligence = 10, wisdom = 10, charisma = 10) => ({
  strength,
  dexterity,
  constitution,
  intelligence,
  wisdom,
  charisma,
});

const melee = (name, damage, {
  reach = 5,
  lengthFt,
  attackBonus = 2,
  damageType = "",
  usableInClose,
  usableInClinch,
  requiresOpenMelee,
  chargeOnly,
  naturalWeapon,
} = {}) => ({
  name,
  kind: "melee",
  attackType: "melee",
  reach,
  ...(Number.isFinite(lengthFt) ? { lengthFt } : {}),
  attackBonus,
  damage,
  damageType,
  ...(usableInClose !== undefined ? { usableInClose } : {}),
  ...(usableInClinch !== undefined ? { usableInClinch } : {}),
  ...(requiresOpenMelee !== undefined ? { requiresOpenMelee } : {}),
  ...(chargeOnly !== undefined ? { chargeOnly } : {}),
  ...(naturalWeapon !== undefined ? { naturalWeapon } : {}),
});

const ranged = (name, damage, normal, long, { attackBonus = 2, damageType = "piercing", ammunition = "arrows" } = {}) => ({
  name,
  kind: "ranged",
  attackType: "ranged",
  attackBonus,
  damage,
  damageType,
  ammunition,
  rangeProfile: { normal, long },
});

const actor = ({
  id,
  actorKey,
  name,
  category,
  source = "normalized-legacy-actor",
  sourceLabel = "Normalized Legacy Actor",
  teamDefault = "enemy",
  playable = true,
  defaultControlMode = "ai",
  modelKey,
  size = "medium",
  movementModes = ["ground"],
  movement = { ground: 30 },
  attributes,
  abilityScores,
  derivedStats,
  compatibilityAttributes = {},
  equipment = [],
  equippedArmor,
  equippedShield,
  armorProfile,
  attacks = [],
  bonuses,
  maxStamina,
  currentStamina,
  staminaConfigured,
  actionsPerRound,
  rangeProfile = {},
  aiRole = "melee",
  tags = [],
  traits = [],
  visual = {},
}) => ({
  id,
  actorKey: actorKey || (getCanonicalCombatActorDefinition(id) ? id : undefined),
  sourceActorKey: actorKey || (getCanonicalCombatActorDefinition(id) ? id : undefined),
  name,
  category,
  source,
  sourceLabel,
  teamDefault,
  playable,
  defaultControlMode,
  modelKey: modelKey || id,
  size,
  movementModes,
  movement,
  ...(attributes ? { attributes } : {}),
  abilityScores,
  derivedStats,
  compatibilityAttributes,
  equipment,
  ...(equippedArmor ? { equippedArmor } : {}),
  ...(equippedShield ? { equippedShield } : {}),
  ...(armorProfile ? { armorProfile } : {}),
  attacks,
  ...(bonuses ? { bonuses } : {}),
  ...(Number.isFinite(maxStamina) ? { maxStamina } : {}),
  ...(Number.isFinite(currentStamina) ? { currentStamina } : {}),
  ...(staminaConfigured !== undefined ? { staminaConfigured } : {}),
  ...(Number.isFinite(actionsPerRound) ? { actionsPerRound } : {}),
  rangeProfile,
  aiRole,
  tags: [...new Set([...tags, "playable"])],
  traits: [...traits],
  visual: {
    modelUrl: visual.modelUrl || HUMAN_MODEL,
    desiredHeightFt: visual.desiredHeightFt || 5.8,
    yawOffsetDeg: visual.yawOffsetDeg || 0,
  },
});

