const HUMAN_MODEL = "/assets/models/characters/human_base_morph.glb";
const HAWK_MODEL = "/assets/models/characters/hawk_flying.glb";

const abilities = (strength, dexterity, constitution, intelligence = 10, wisdom = 10, charisma = 10) => ({
  strength,
  dexterity,
  constitution,
  intelligence,
  wisdom,
  charisma,
});

const melee = (name, damage, { reach = 5, lengthFt, attackBonus = 2, damageType = "" } = {}) => ({
  name,
  kind: "melee",
  attackType: "melee",
  reach,
  ...(Number.isFinite(lengthFt) ? { lengthFt } : {}),
  attackBonus,
  damage,
  damageType,
});

const ranged = (name, damage, normal, long, { attackBonus = 2, damageType = "piercing", ammunition = "arrows" } = {}) => ({
  name,
  kind: "ranged",
  attackType: "ranged",
  attackBonus,
  damage,
  damageType,
  ammunition,
  rangeProfile: { normal, long },
});

const actor = ({
  id,
  name,
  category,
  source = "normalized-legacy-actor",
  sourceLabel = "Normalized Legacy Actor",
  teamDefault = "enemy",
  playable = true,
  defaultControlMode = "ai",
  modelKey,
  size = "medium",
  movementModes = ["ground"],
  movement = { ground: 30 },
  abilityScores,
  derivedStats,
  compatibilityAttributes = {},
  equipment = [],
  attacks = [],
  rangeProfile = {},
  aiRole = "melee",
  tags = [],
  visual = {},
}) => ({
  id,
  name,
  category,
  source,
  sourceLabel,
  teamDefault,
  playable,
  defaultControlMode,
  modelKey: modelKey || id,
  size,
  movementModes,
  movement,
  abilityScores,
  derivedStats,
  compatibilityAttributes,
  equipment,
  attacks,
  rangeProfile,
  aiRole,
  tags: [...new Set([...tags, "playable"])],
  visual: {
    modelUrl: visual.modelUrl || HUMAN_MODEL,
    desiredHeightFt: visual.desiredHeightFt || 5.8,
    yawOffsetDeg: visual.yawOffsetDeg || 0,
  },
});

